import { LAUNCHPAD_COMPONENT, LAUNCHPAD_CONTROLLER, LAUNCHPAD_CSS, LAUNCHPAD_LOGO, LAUNCHPAD_VIEW, launchpadIndexHtml, launchpadManifest } from "./ui.js";

export interface LaunchpadOptions {
  /** Folder of the @rap-transpiler/runtime package (default: next to the compiler). */
  runtimeDir?: string;
  /** The output folder: docker-compose builds the applications from their folders, relative to it. */
  outDir?: string;
  /** The applications built from their sources (D67), by id. */
  built?: Map<string, BuiltApp>;
}

export interface LaunchpadResult {
  diagnostics: Diagnostics;
  model?: LaunchpadModel;
  files: Array<{ path: string; content: string }>;
}

const SERVER = `#!/usr/bin/env node
// Generated by rap-transpiler: starts the launchpad of the applications.
// Configuration by environment variables: see README.md and .env.example.
import { fileURLToPath } from "node:url";
import { startLaunchpad } from "@rap-transpiler/runtime";

const launchpad = await startLaunchpad({ dir: fileURLToPath(new URL(".", import.meta.url)) });
console.log(\`Launchpad ready at \${launchpad.url}\`);
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.once(signal, () => {
    launchpad.close().then(() => process.exit(0), () => process.exit(1));
  });
}
`;

const DOCKERFILE = `# syntax=docker/dockerfile:1
# Generated by rap-transpiler.
FROM node:22-alpine AS dependencies
WORKDIR /app
COPY package.json .npmrc ./
COPY vendor ./vendor
RUN npm install --omit=dev --omit=optional --no-audit --no-fund

FROM node:22-alpine
ENV NODE_ENV=production PORT=8090
WORKDIR /app
COPY --from=dependencies /app/node_modules ./node_modules
COPY . .
USER node
EXPOSE 8090
HEALTHCHECK --interval=10s --timeout=3s --retries=5 CMD wget -qO- http://127.0.0.1:8090/health || exit 1
CMD ["node", "server.mjs"]
`;

const DOCKERIGNORE = `node_modules
.env
`;

const posix = (p: string): string => p.split(path.sep).join("/");

/** The applications with a generated folder run in docker-compose, behind the launchpad. */
function compose(name: string, model: LaunchpadModel, apps: ResolvedApp[], outDir: string | undefined): string {
  const local = apps.filter((a) => a.build !== undefined && outDir !== undefined);
  const lines = [
    "# Generated by rap-transpiler.",
    "#   docker compose up --build                      launchpad, applications and PostgreSQL, no login (AUTH_MODE=none)",
    "#   AUTH_MODE=oidc docker compose --profile oidc up --build",
    "#                                                  with Keycloak (user alice / alice), see README.md",
    "# The applications behind the launchpad share its login: same client, public URL and SESSION_SECRET.",
    "x-login: &login",
    "  AUTH_MODE: ${AUTH_MODE:-none}",
    "  OIDC_ISSUER: http://localhost:8180/realms/rapt",
    "  OIDC_DISCOVERY_URL: http://keycloak:8080/realms/rapt/.well-known/openid-configuration",
    "  OIDC_CLIENT_ID: rapt-launchpad",
    "  OIDC_CLIENT_SECRET: rapt-launchpad-secret",
    "  SESSION_SECRET: ${SESSION_SECRET:-change-me-change-me-change-me-change-me}",
    "  PUBLIC_URL: http://localhost:8090/",
    "",
    "services:",
    "  launchpad:",
    "    build: .",
    `    image: ${name}:latest`,
    "    environment:",
    "      <<: *login",
    ...model.apps.map((a) => `      ${appUrlVariable(a.id)}: ${local.some((l) => l.id === a.id) ? `http://${a.id}:8080/` : a.url}`),
    "    ports:",
    '      - "8090:8090"',
  ];
  if (local.length > 0) {
    lines.push("    depends_on:", ...local.flatMap((a) => [`      ${a.id}:`, "        condition: service_healthy"]));
  }
  for (const app of local) {
    lines.push(
      "",
      `  ${app.id}:`,
      `    build: ${posix(path.relative(outDir as string, app.build as string)) || "."}`,
      "    environment:",
      "      <<: *login",
      `      DATABASE_URL: postgres://app:app@db-${app.id}:5432/app`,
      "    depends_on:",
      `      db-${app.id}:`,
      "        condition: service_healthy",
      "",
      `  db-${app.id}:`,
      "    image: postgres:16-alpine",
      "    environment:",
      "      POSTGRES_DB: app",
      "      POSTGRES_USER: app",
      "      POSTGRES_PASSWORD: app",
      "    healthcheck:",
      '      test: ["CMD-SHELL", "pg_isready -U app -d app"]',
      "      interval: 5s",
      "      retries: 20",
      "    volumes:",
      `      - db-${app.id}-data:/var/lib/postgresql/data`,
    );
  }
  lines.push(
    "",
    "  keycloak:",
    "    image: quay.io/keycloak/keycloak:26.0",
    '    profiles: ["oidc"]',
    "    command: start-dev --import-realm",
    "    environment:",
    "      KC_BOOTSTRAP_ADMIN_USERNAME: admin",
    "      KC_BOOTSTRAP_ADMIN_PASSWORD: admin",
    "      KC_HOSTNAME: http://localhost:8180",
    '      KC_HOSTNAME_BACKCHANNEL_DYNAMIC: "true"',
    "    volumes:",
    "      - ./keycloak:/opt/keycloak/data/import:ro",
    "    ports:",
    '      - "8180:8080"',
  );
  if (local.length > 0) {
    lines.push("", "volumes:", ...local.map((a) => `  db-${a.id}-data:`));
  }
  return `${lines.join("\n")}\n`;
}

function envExample(model: LaunchpadModel): string {
  return `# Configuration of the generated launchpad (all optional).
PORT=8090
PUBLIC_URL=http://localhost:8090/
LOG_LEVEL=info
# none (development user DEV_USER, its roles DEV_ROLES — default: every tile) or oidc
AUTH_MODE=none
DEV_USER=DEVELOPER
# DEV_ROLES=travel_viewer
OIDC_ISSUER=http://localhost:8180/realms/rapt
OIDC_DISCOVERY_URL=
OIDC_CLIENT_ID=rapt-launchpad
OIDC_CLIENT_SECRET=rapt-launchpad-secret
OIDC_REQUIRED_ROLE=
# the same secret in the applications behind the launchpad: they read its sessions
SESSION_SECRET=change-me-change-me-change-me-change-me
# where the launchpad reaches the applications
${model.apps.map((a) => `${appUrlVariable(a.id)}=${a.url}`).join("\n")}
`;
}

function readme(name: string, model: LaunchpadModel): string {
  const tiles = model.groups.flatMap((g) => g.tiles.map((t) => ({ group: g.title, tile: t })));
  return `# ${name}

Launchpad generated by [rap-transpiler](https://github.com/clementringot/rap-transpiler): the entry
point of the applications, as the SAP Fiori launchpad, built with OpenUI5. It shows the tiles
assigned to the roles of the user, opens the applications at \`/apps/<id>/\` and forwards the
requests of their UIs to their services: the browser sees a single origin and logs in once.

## Run

With Docker (the applications generated next to it are built and started too):

\`\`\`sh
docker compose up --build          # http://localhost:8090/ (no login)
AUTH_MODE=oidc docker compose --profile oidc up --build   # Keycloak, user alice / alice
\`\`\`

With Node.js 22, the applications running: \`npm install\` then \`npm start\`
(\`APP_<ID>_URL\` gives where each application runs).

## The applications behind the launchpad

The launchpad opens the session (OIDC, authorization code with PKCE) and the applications read it:
they need the same \`SESSION_SECRET\`, \`AUTH_MODE=oidc\` with the same issuer, and the client and
\`PUBLIC_URL\` of the launchpad (a login asked by an application then comes back to it). The claims
the authorizations of the applications read are kept in the session: ${model.claims.length === 0 ? "none" : model.claims.map((c) => `\`${c}\``).join(", ")}.

| Application | Mounted at | Services | Variable |
|---|---|---|---|
${model.apps.map((a) => `| ${a.title} | \`/apps/${a.id}/\` | ${a.servicePaths.map((p) => `\`${p}\``).join("<br>") || "—"} | \`${appUrlVariable(a.id)}\` |`).join("\n")}

## Tiles

A tile is shown to the users having one of its roles (every user without roles); \`/go/<intent>\`
and \`/#<intent>\` open the application of an intent.

| Group | Tile | Intent | Roles | Count |
|---|---|---|---|---|
${tiles.map(({ group, tile }) => `| ${group} | ${tile.title} | ${tile.intent === undefined ? "" : `\`${tile.intent}\``} | ${tile.roles.length === 0 ? "every user" : tile.roles.map((r) => `\`${r}\``).join(", ")} | ${tile.count === undefined ? "" : `\`${tile.count}\``} |`).join("\n")}

${deploySection(name, "launchpad")}
On Cloud Foundry, each application is pushed on its own route; give their routes to the
launchpad with \`cf set-env ${name} APP_<ID>_URL https://…\`.

## Content

| Path | Content |
|---|---|
| \`launchpad/config.json\` | the tiles, groups and applications, read by the server |
| \`ui/\` | OpenUI5 launchpad |
| \`keycloak/rapt-realm.json\` | realm of the Keycloak of docker-compose (client \`rapt-launchpad\`) |
| \`vendor/\` | the rap-transpiler runtime (MIT) |
`;
}

/** The files of the OpenUI5 launchpad (`ui/`), served by the launchpad server. */
export function generateLaunchpadUi(model: LaunchpadModel): Array<{ path: string; content: string }> {
  return [
    { path: "index.html", content: launchpadIndexHtml(model.title) },
    { path: "manifest.json", content: launchpadManifest(model.title) },
    { path: "Component.js", content: LAUNCHPAD_COMPONENT },
    { path: "view/Launchpad.view.xml", content: LAUNCHPAD_VIEW },
    { path: "controller/Launchpad.controller.js", content: LAUNCHPAD_CONTROLLER },
    { path: "css/style.css", content: LAUNCHPAD_CSS },
    { path: "logo.svg", content: LAUNCHPAD_LOGO },
  ];
}

/** Resolves `launchpad.json` and generates the files of the launchpad. */
export function generateLaunchpad(file: string, options: LaunchpadOptions = {}): LaunchpadResult {
  const diagnostics = new Diagnostics();
  const resolution = resolveLaunchpad(file, diagnostics, options.built === undefined ? {} : { built: options.built });
  if (resolution === undefined || diagnostics.hasErrors()) {
    return resolution === undefined ? { diagnostics, files: [] } : { diagnostics, model: resolution.model, files: [] };
  }
  const { model, apps } = resolution;
  const runtimeDir = packageDir("@rap-transpiler/runtime", "runtime", options.runtimeDir);
  const modelDir = packageDir("@rap-transpiler/model", "model");
  if (runtimeDir === undefined || modelDir === undefined) {
    diagnostics.error("APP001", "the @rap-transpiler/runtime and @rap-transpiler/model packages (built: dist/) are needed to embed the runtime; give --runtime <dir> or run pnpm build");
    return { diagnostics, model, files: [] };
  }
  const runtime = JSON.parse(readFileSync(path.join(runtimeDir, "package.json"), "utf8")) as PackageJson;
  const version = (dependency: string): string => runtime.dependencies?.[dependency] ?? runtime.devDependencies?.[dependency] ?? "*";
  const slug = model.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  const name = slug === "" ? "rapt-launchpad" : slug.includes("launchpad") ? slug : `${slug}-launchpad`;
  const openui5 = Object.keys(runtime.devDependencies ?? {}).filter((d) => d.startsWith("@openui5/"));
  const pkg = {
    name,
    version: "1.0.0",
    private: true,
    description: `${/launchpad/i.test(model.title) ? model.title : `Launchpad ${model.title}`}, generated by rap-transpiler`,
    type: "module",
    engines: { node: ">=22" },
    scripts: { start: "node server.mjs" },
    dependencies: {
      "@rap-transpiler/runtime": "file:vendor/rap-transpiler-runtime",
      "@rap-transpiler/model": "file:vendor/rap-transpiler-model",
      ...Object.fromEntries(openui5.map((d) => [d, version(d)])),
      "less-openui5": version("less-openui5"),
    },
    overrides: { "@rap-transpiler/model": "$@rap-transpiler/model" },
  };
  const realm = keycloakRealm({ clientId: "rapt-launchpad", clientName: "Launchpad generated by rap-transpiler", secret: "rapt-launchpad-secret", url: "http://localhost:8090", roles: model.roles, claims: model.claims });
  const files = [
    { path: "package.json", content: `${JSON.stringify(pkg, null, 2)}\n` },
    { path: ".npmrc", content: "install-links=true\n" },
    { path: "server.mjs", content: SERVER },
    { path: "launchpad/config.json", content: `${JSON.stringify(model, null, 2)}\n` },
    ...generateLaunchpadUi(model).map((f) => ({ path: `ui/${f.path}`, content: f.content })),
    { path: "Dockerfile", content: DOCKERFILE },
    // the applications built with it (D67) have their own image and route
    { path: ".dockerignore", content: `${DOCKERIGNORE}${options.built?.size ? "apps\n" : ""}` },
    { path: "manifest.yml", content: cloudFoundryManifest(name, { database: false, memory: "256M" }) },
    { path: ".cfignore", content: `${CFIGNORE}${options.built?.size ? "apps\n" : ""}` },
    { path: "docker-compose.yml", content: compose(name, model, apps, options.outDir === undefined ? undefined : path.resolve(options.outDir)) },
    { path: "keycloak/rapt-realm.json", content: `${JSON.stringify(realm, null, 2)}\n` },
    { path: ".env.example", content: envExample(model) },
    { path: "README.md", content: readme(name, model) },
    ...vendorPackage(modelDir, "rap-transpiler-model", {}),
    ...vendorPackage(runtimeDir, "rap-transpiler-runtime", { "@rap-transpiler/model": "file:../rap-transpiler-model" }),
  ];
  return { diagnostics, model, files };
}

export interface LaunchpadBuildResult extends LaunchpadResult {
  /** The applications built from their sources, into apps/<id>/ of the output folder. */
  apps: Array<{ id: string; source: string; out: string; files: number }>;
}

const APP_ID = /^[a-z][a-z0-9-]*$/;

/**
 * `rapt launchpad`: the launchpad and, built from their sources (`source`, D67) into
 * `apps/<id>/`, its applications. A single folder to deploy: docker-compose starts them all.
 */
export async function buildLaunchpad(file: string, options: LaunchpadOptions & { outDir: string }): Promise<LaunchpadBuildResult> {
  const diagnostics = new Diagnostics();
  const at = { file };
  let entries: unknown[] = [];
  try {
    const source = JSON.parse(readFileSync(file, "utf8")) as { apps?: unknown };
    entries = Array.isArray(source?.apps) ? source.apps : [];
  } catch {
    // reported by resolveLaunchpad
  }
  const base = path.dirname(path.resolve(file));
  const outDir = path.resolve(options.outDir);
  const built = new Map<string, BuiltApp>();
  const files: Array<{ path: string; content: string }> = [];
  const apps: LaunchpadBuildResult["apps"] = [];
  for (const entry of entries as Array<Record<string, unknown> | null>) {
    const id = entry?.["id"];
    const source = entry?.["source"];
    if (typeof id !== "string" || !APP_ID.test(id) || typeof source !== "string" || source.trim() === "" || entry?.["build"] !== undefined || built.has(id)) {
      continue;
    }
    const dir = path.resolve(base, source);
    if (!existsSync(dir)) {
      diagnostics.error("LPD009", `the application ${id}: no folder ${source} (source, relative to launchpad.json)`, at);
      continue;
    }
    const service = entry?.["service"];
    const result = await generateApplication(loadProject(dir), {
      ...(typeof service === "string" ? { service } : {}),
      ...(options.runtimeDir === undefined ? {} : { runtimeDir: options.runtimeDir }),
    });
    for (const d of result.diagnostics.items) {
      if (d.severity !== "info") {
        diagnostics.add(d.severity, d.code, `${id}: ${d.message}`, { file: d.file === undefined ? dir : path.join(dir, ...d.file.split("/")), ...(d.line === undefined ? {} : { line: d.line }), ...(d.column === undefined ? {} : { column: d.column }) });
      }
    }
    if (result.model === undefined || result.files.length === 0) {
      diagnostics.error("LPD009", `the application ${id} does not build (rapt check ${source})`, at);
      continue;
    }
    let title: string | undefined;
    try {
      title = (JSON.parse(result.files.find((f) => f.path === "ui/manifest.json")?.content ?? "") as { "sap.app"?: { title?: string } })["sap.app"]?.title;
    } catch {
      // an application without UI (Web API)
    }
    built.set(id, { dir: path.join(outDir, "apps", id), model: result.model, ...(title === undefined ? {} : { title }) });
    files.push(...result.files.map((f) => ({ path: `apps/${id}/${f.path}`, content: f.content })));
    apps.push({ id, source: dir, out: path.join(outDir, "apps", id), files: result.files.length });
  }
  const launchpad = generateLaunchpad(file, { ...options, built });
  diagnostics.addAll(launchpad.diagnostics);
  const model = launchpad.model === undefined ? {} : { model: launchpad.model };
  if (diagnostics.hasErrors() || launchpad.files.length === 0) {
    return { diagnostics, ...model, files: [], apps };
  }
  return { diagnostics, ...model, files: [...launchpad.files, ...files], apps };
}
