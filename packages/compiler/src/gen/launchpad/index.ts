/**
 * `rapt launchpad`: the folder of a launchpad of applications (decision D37). Its server (the
 * runtime, embedded in `vendor/`) serves the OpenUI5 launchpad, opens the sessions the
 * applications read and forwards their requests; docker-compose starts it with the applications
 * built by `rapt build` (one PostgreSQL each) and, in the `oidc` profile, Keycloak.
 */

import { CFIGNORE, cloudFoundryManifest, deploySection } from "../deploy.js";
