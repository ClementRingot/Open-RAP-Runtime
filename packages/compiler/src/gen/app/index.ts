function authorizationsSection(model: Model): string {
  const roles = model.authorizations?.roles ?? [];
  if (roles.length === 0) {
    return "";
  }
  const claims = authorizationClaims(model.authorizations);
  return `
## Authorizations

The behavior pool checks authorization objects (AUTHORITY-CHECK). The roles of the identity
provider give the authorizations of \`rapt/authorizations.json\` (in \`model/model.json\`; replace
them with \`AUTHORIZATIONS_FILE\`). In the Keycloak of docker-compose, \`alice\` has every role.

| Role | Description |
|---|---|
${roles.map((r) => `| \`${r.name}\` | ${r.description ?? ""} |`).join("\n")}
${claims.length === 0 ? "" : `
Values read from the token: ${claims.map((c) => `\`${c}\``).join(", ")} — in Keycloak, a user attribute of the same name (Users → user → Attributes).
`}`;
}

function destinationsSection(destinations: string[]): string {
  const rows = destinations.map((d) => `| \`${d}\` | ${destinationKeys(d).map((k) => `\`DESTINATION_${k}_URL\``).join(", then ")} |`);
  return `
## Remote APIs

The behavior pool calls remote APIs (HTTP client, OData client proxy). Each destination is
configured by environment variables: \`DESTINATION_<NAME>_URL\`, then \`_USER\` and \`_PASSWORD\`
(basic authentication), \`_TOKEN\` (bearer token) or \`_HEADERS\` (a JSON object of headers, an
API key for example). The credentials stay in the server: the ABAP code only sees the URL.
${rows.length === 0 ? "" : `
| Destination in the ABAP code | Variable |
|---|---|
${rows.join("\n")}
`}`;
}

