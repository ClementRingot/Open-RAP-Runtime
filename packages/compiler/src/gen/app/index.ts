function readme(model: Model, name: string): string {
  return `# ${name}

Application generated by [rap-transpiler](https://github.com/clementringot/rap-transpiler) from the
RAP service definition \`${model.service.name}\`: an OData V4 service (\`${model.service.path}\`), the
managed RAP runtime with the transpiled behavior pool, and an OpenUI5 UI (List Report / Object
Page) at \`/ui/\`.

## Run

With Docker:

\`\`\`sh
docker compose up --build          # http://localhost:8080/ (no login)
\`\`\`

With Node.js 22 and a PostgreSQL database:

\`\`\`sh
npm install
DATABASE_URL=postgres://user:password@localhost:5432/app npm start
\`\`\`

For a quick try without PostgreSQL: \`npm install\` (with its optional dependencies) then
\`PGLITE_DIR=./data npm start\` (embedded PostgreSQL, development only).

## Login (OIDC)

\`AUTH_MODE=oidc\` checks bearer tokens of API clients and opens browser sessions (authorization
code with PKCE). With the Keycloak of docker-compose (realm \`rapt\`, user \`alice\` / \`alice\`):

\`\`\`sh
AUTH_MODE=oidc docker compose --profile oidc up --build
\`\`\`

The variables are listed in \`.env.example\`.

## Content

| Folder | Content |
|---|---|
| \`model/model.json\` | intermediate representation read by the runtime |
| \`db/schema.sql\` | PostgreSQL tables and views (applied at start-up unless \`SCHEMA=skip\`) |
| \`odata/metadata.xml\` | \`$metadata\` of the service |
| \`abap/\` | transpiled behavior pool; \`abap/src/\` holds the ABAP given to the transpiler |
| \`ui/\` | OpenUI5 application |
| \`vendor/\` | the rap-transpiler runtime (MIT) |
`;
}

export function generateScaffold(model: Model, diagnostics: Diagnostics, options: ScaffoldOptions = {}): Array<{ path: string; content: string }> {
  const runtimeDir = packageDir("@rap-transpiler/runtime", "runtime", options.runtimeDir);
  const modelDir = packageDir("@rap-transpiler/model", "model");
  if (runtimeDir === undefined || modelDir === undefined) {
    diagnostics.error("APP001", "the @rap-transpiler/runtime and @rap-transpiler/model packages (built: dist/) are needed to embed the runtime; give --runtime <dir> or run pnpm build");
    return [];
  }
  const runtime = JSON.parse(readFileSync(path.join(runtimeDir, "package.json"), "utf8")) as PackageJson;
  const version = (name: string): string => runtime.dependencies?.[name] ?? runtime.devDependencies?.[name] ?? "*";
  const name = (model.service.binding || model.service.name).toLowerCase().replace(/[^a-z0-9._-]+/g, "-").replace(/^[._-]+/, "") || "rapt-app";
  const openui5 = Object.keys(runtime.devDependencies ?? {}).filter((d) => d.startsWith("@openui5/"));
  const pkg = {
    name,
    version: "1.0.0",
    private: true,
    description: `OData V4 service ${model.service.name}, generated by rap-transpiler`,
    type: "module",
    engines: { node: ">=22" },
    scripts: { start: "node server.mjs" },
    dependencies: {
      "@rap-transpiler/runtime": "file:vendor/rap-transpiler-runtime",
      "@rap-transpiler/model": "file:vendor/rap-transpiler-model",
      "@abaplint/runtime": version("@abaplint/runtime"),
      ...Object.fromEntries(openui5.map((d) => [d, version(d)])),
      "less-openui5": version("less-openui5"),
    },
    optionalDependencies: { "@electric-sql/pglite": version("@electric-sql/pglite") },
    overrides: { "@rap-transpiler/model": "$@rap-transpiler/model" },
  };
  return [
    { path: "package.json", content: `${JSON.stringify(pkg, null, 2)}\n` },
    { path: ".npmrc", content: "install-links=true\n" },
    { path: "server.mjs", content: SERVER },
    { path: "Dockerfile", content: DOCKERFILE },
    { path: ".dockerignore", content: DOCKERIGNORE },
    { path: "docker-compose.yml", content: compose(name) },
    { path: "keycloak/rapt-realm.json", content: `${JSON.stringify(REALM, null, 2)}\n` },
    { path: ".env.example", content: ENV_EXAMPLE },
    { path: "README.md", content: readme(model, name) },
    ...vendorPackage(modelDir, "rap-transpiler-model", {}),
    ...vendorPackage(runtimeDir, "rap-transpiler-runtime", { "@rap-transpiler/model": "file:../rap-transpiler-model" }),
  ];
}
