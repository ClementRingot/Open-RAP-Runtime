export function generateScaffold(model: Model, diagnostics: Diagnostics, options: ScaffoldOptions = {}): Array<{ path: string; content: string }> {
  const runtimeDir = packageDir("@open-rap/runtime", "runtime", options.runtimeDir);
  const modelDir = packageDir("@open-rap/model", "model");
  if (runtimeDir === undefined || modelDir === undefined) {
    diagnostics.error("APP001", "the @open-rap/runtime and @open-rap/model packages (built: dist/) are needed to embed the runtime; give --runtime <dir> or run pnpm build");
    return [];
  }
  const runtime = JSON.parse(readFileSync(path.join(runtimeDir, "package.json"), "utf8")) as PackageJson;
  const version = (name: string): string => runtime.dependencies?.[name] ?? runtime.devDependencies?.[name] ?? "*";
  const name = (model.service.binding || model.service.name).toLowerCase().replace(/[^a-z0-9._-]+/g, "-").replace(/^[._-]+/, "") || "rapt-app";
  const openui5 = Object.keys(runtime.devDependencies ?? {}).filter((d) => d.startsWith("@openui5/"));
  const pkg = {
    name,
    version: "1.0.0",
    private: true,
    description: `OData V4 service ${model.service.name}, generated by Open RAP Runtime`,
    type: "module",
    engines: { node: ">=22" },
    scripts: { start: "node server.mjs" },
    dependencies: {
      "@open-rap/runtime": "file:vendor/open-rap-runtime",
      "@open-rap/model": "file:vendor/open-rap-model",
      "@abaplint/runtime": version("@abaplint/runtime"),
      ...Object.fromEntries(openui5.map((d) => [d, version(d)])),
      "less-openui5": version("less-openui5"),
    },
    optionalDependencies: { "@electric-sql/pglite": version("@electric-sql/pglite") },
    overrides: { "@open-rap/model": "$@open-rap/model" },
  };
  return [
    { path: "package.json", content: `${JSON.stringify(pkg, null, 2)}\n` },
    { path: ".npmrc", content: "install-links=true\n" },
    { path: "server.mjs", content: SERVER },
    { path: "Dockerfile", content: DOCKERFILE },
    { path: ".dockerignore", content: DOCKERIGNORE },
    { path: "manifest.yml", content: cloudFoundryManifest(name, { database: true }) },
    { path: ".cfignore", content: CFIGNORE },
    { path: "docker-compose.yml", content: compose(name) },
    { path: "keycloak/rapt-realm.json", content: `${JSON.stringify(realm(model), null, 2)}\n` },
    { path: ".env.example", content: `${ENV_EXAMPLE}${destinationLines(options.destinations ?? [])}${model.services?.mail === true ? MAIL_LINES : ""}` },
    { path: "README.md", content: readme(model, name, options.destinations ?? []) },
    ...vendorPackage(modelDir, "open-rap-model", {}),
    ...vendorPackage(runtimeDir, "open-rap-runtime", { "@open-rap/model": "file:../open-rap-model" }),
  ];
}
