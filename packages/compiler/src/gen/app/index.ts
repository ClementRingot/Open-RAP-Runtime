export interface ScaffoldOptions {
  /** Folder of the @open-rap/runtime package (default: next to the compiler). */
  runtimeDir?: string;
  /** Destinations of the remote APIs called by the behavior pools (D31), see findDestinations. */
  destinations?: string[];
}

/**
 * The destinations the ABAP code names with literals: `create_by_cloud_destination( i_name = '…' )`
 * and `create_by_comm_arrangement( comm_scenario = '…' service_id = '…' )` (`SCENARIO.SERVICE`).
 * Names given by variables are not found; the application reports them at run time.
 */
export function findDestinations(sources: ReadonlyArray<{ content: string }>): string[] {
  const names = new Set<string>();
  const value = (call: string, parameter: string): string | undefined => new RegExp(`\\b${parameter}\\s*=\\s*['\`]([^'\`]+)['\`]`, "i").exec(call)?.[1];
  for (const { content } of sources) {
    const code = content.replace(/^\*.*$/gm, "").replace(/"[^\n]*$/gm, "");
    for (const match of code.matchAll(/\b(create_by_cloud_destination|create_by_comm_arrangement)\s*\(([^)]*)\)/gi)) {
      const call = match[2] ?? "";
      if ((match[1] ?? "").toLowerCase() === "create_by_cloud_destination") {
        const name = value(call, "i_name");
        if (name !== undefined) {
          names.add(name);
        }
      } else {
        const scenario = value(call, "comm_scenario");
        const service = value(call, "service_id");
        if (scenario !== undefined) {
          names.add(service === undefined ? scenario : `${scenario}.${service}`);
        }
      }
    }
  }
  return [...names].sort();
}

/** The lines of .env.example for the destinations. */
function destinationLines(destinations: string[]): string {
  if (destinations.length === 0) {
    return "";
  }
  const lines = [
    "# Destinations of the remote APIs called by the behavior pool: the URL, then basic",
    "# authentication (_USER, _PASSWORD), a bearer token (_TOKEN) or further headers (_HEADERS, JSON).",
    "# Behind an outbound proxy: HTTPS_PROXY=... and NODE_USE_ENV_PROXY=1.",
  ];
  for (const name of destinations) {
    const [key = ""] = destinationKeys(name);
    lines.push(`# ${name}${destinationKeys(name).length > 1 ? ` (or DESTINATION_${destinationKeys(name)[1]}_URL for the whole scenario)` : ""}`);
    lines.push(`DESTINATION_${key}_URL=`, `# DESTINATION_${key}_USER=`, `# DESTINATION_${key}_PASSWORD=`, `# DESTINATION_${key}_TOKEN=`, `# DESTINATION_${key}_HEADERS={"APIKey":"..."}`);
  }
  return `${lines.join("\n")}\n`;
}

