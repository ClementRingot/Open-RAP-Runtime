/**
 * The database of the ABAP SQL of the behavior pools (decision D26): a read-only database client
 * of @abaplint/runtime over the transaction of the running LUW.
 *
 * @abaplint/transpiler turns a SELECT into SQL text with its values in ABAP form (dates
 * `YYYYMMDD`, UUIDs as hexadecimal digits) and a few ABAP keywords (`UP TO n ROWS`, `EQ`,
 * `ORDER BY PRIMARY KEY`). The tables and CDS entities are read through the views of the ABAP SQL
 * schema, whose columns hold the ABAP form (generated with the database schema); the text is
 * translated to PostgreSQL here. Each statement runs in a savepoint: a failing SELECT leaves the
 * LUW's transaction usable.
 */

import { sql, type Kysely } from "kysely";
import { ABAP_SQL_SCHEMA } from "@rap-transpiler/model";
import { withSavepoint } from "../db/database.js";

export type AbapSqlValue = number | string | null;
export type AbapSqlRow = Record<string, AbapSqlValue>;

export interface AbapSelectOptions {
  /** The SELECT, as generated by the transpiler. */
  select: string;
  /** Key columns (lower case) of the table, for `ORDER BY PRIMARY KEY`. */
  primaryKey?: string[];
}

export class AbapSqlError extends Error {}

interface Token {
  kind: "literal" | "identifier" | "word" | "space" | "symbol";
  text: string;
}

const WORD = /[A-Za-z0-9_$#]/;

function tokenize(text: string): Token[] {
  const tokens: Token[] = [];
  let i = 0;
  while (i < text.length) {
    const c = text[i] as string;
    if (c === "'" || c === '"') {
      let j = i + 1;
      while (j < text.length && !(text[j] === c && text[j + 1] !== c)) {
        j += text[j] === c ? 2 : 1;
      }
      if (j >= text.length) {
        throw new AbapSqlError(`unterminated ${c === "'" ? "literal" : "identifier"} in ${text}`);
      }
      const value = text.slice(i, j + 1);
      tokens.push(c === "'" ? { kind: "literal", text: value } : { kind: "identifier", text: value.toLowerCase() });
      i = j + 1;
    } else if (/\s/.test(c)) {
      let j = i;
      while (j < text.length && /\s/.test(text[j] as string)) {
        j++;
      }
      tokens.push({ kind: "space", text: " " });
      i = j;
    } else if (WORD.test(c)) {
      let j = i;
      while (j < text.length && (WORD.test(text[j] as string) || (text[j] === "." && /\d/.test(c) && /\d/.test(text[j + 1] ?? "")))) {
        j++;
      }
      tokens.push({ kind: "word", text: text.slice(i, j) });
      i = j;
    } else {
      tokens.push({ kind: "symbol", text: c });
      i++;
    }
  }
  return tokens;
}

const COMPARISONS: Record<string, string> = { EQ: "=", NE: "<>", LT: "<", LE: "<=", GT: ">", GE: ">=" };
const ORDER: Record<string, string> = { ASCENDING: "ASC", DESCENDING: "DESC" };
const SCHEMA = `"${ABAP_SQL_SCHEMA}"`;

/**
 * Translates the SQL of the transpiler to PostgreSQL: `UP TO n ROWS` → `LIMIT n` (none for 0),
 * `ORDER BY PRIMARY KEY` → the key columns, `ASCENDING`/`DESCENDING`, the comparison keywords,
 * `alias~field`, identifiers in lower case (ABAP is case-insensitive, the views use lower case).
 * Only the views of the ABAP SQL schema can be read.
 */
export function translateSelect(text: string, primaryKey: string[] = []): string {
  const tokens = tokenize(text);
  const word = (t: Token | undefined, value: string): boolean => t?.kind === "word" && t.text.toUpperCase() === value;
  const significant = (from: number): number => {
    let j = from;
    while (tokens[j]?.kind === "space") {
      j++;
    }
    return j;
  };
  let limit = 0;
  const out: Token[] = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i] as Token;
    if (t.kind === "symbol" && t.text === "~") {
      out.push({ kind: "symbol", text: "." });
      continue;
    }
    if (t.kind !== "word") {
      out.push(t);
      continue;
    }
    const upper = t.text.toUpperCase();
    if (upper === "UP") {
      const to = significant(i + 1);
      const n = significant(to + 1);
      const rows = significant(n + 1);
      if (word(tokens[to], "TO") && /^\d+$/.test(tokens[n]?.text ?? "") && word(tokens[rows], "ROWS")) {
        limit = Number(tokens[n]?.text);
        i = rows;
        continue;
      }
    }
    if (upper === "ORDER") {
      const by = significant(i + 1);
      const next = significant(by + 1);
      if (word(tokens[by], "BY") && word(tokens[next], "ORDER")) {
        // OPEN CURSOR … ORDER BY: the transpiler writes the keywords twice
        i = by;
        continue;
      }
      const key = significant(next + 1);
      if (word(tokens[by], "BY") && word(tokens[next], "PRIMARY") && word(tokens[key], "KEY")) {
        if (primaryKey.length > 0) {
          out.push({ kind: "word", text: `ORDER BY ${primaryKey.map((k) => `"${k.toLowerCase().replace(/"/g, '""')}"`).join(", ")}` });
        }
        i = key;
        continue;
      }
    }
    if (upper === "FROM" || upper === "JOIN") {
      const source = significant(i + 1);
      const dot = tokens[source + 1];
      if (tokens[source]?.text !== SCHEMA || dot?.text !== ".") {
        const name = tokens.slice(source, source + 3).map((x) => x.text).join("");
        throw new AbapSqlError(`ABAP SQL: ${name} is not a table or a CDS entity of the application`);
      }
    }
    const replaced = COMPARISONS[upper] ?? ORDER[upper];
    out.push(replaced === undefined ? t : { kind: "word", text: replaced });
  }
  const translated = out
    .filter((t, n) => t.kind !== "space" || out[n - 1]?.kind !== "space")
    .map((t) => t.text)
    .join("")
    .trim();
  return limit > 0 ? `${translated} LIMIT ${limit}` : translated;
}

/** A value of a result row as @abaplint/runtime sets it into ABAP data objects. */
function abapValue(value: unknown): AbapSqlValue {
  if (value === null || value === undefined) {
    return null;
  }
  if (typeof value === "number" || typeof value === "string") {
    return value;
  }
  if (typeof value === "boolean") {
    return value ? "X" : "";
  }
  if (typeof value === "bigint") {
    return value.toString();
  }
  if (value instanceof Uint8Array) {
    return Buffer.from(value).toString("hex").toUpperCase();
  }
  return String(value);
}

const READ_ONLY = "ABAP SQL in a behavior pool only reads (decision D26): the RAP runtime writes the business objects";

/**
 * The DEFAULT database connection of the transpiled code (`DatabaseClient` of @abaplint/runtime).
 * `connection` gives the transaction of the running LUW.
 */
export class AbapSqlClient {
  public readonly name = "postgres";

  public constructor(private readonly connection: () => Kysely<unknown>) {}

  public async connect(): Promise<void> {}

  public async disconnect(): Promise<void> {}

  /** The LUW owns the transaction: nothing to begin. */
  public async beginTransaction(): Promise<void> {}

  /** COMMIT WORK: the RAP runtime ends the LUW, a handler cannot (a runtime error in RAP too). */
  public async commit(): Promise<void> {
    throw new AbapSqlError("COMMIT WORK is not allowed in a behavior pool: the RAP runtime ends the LUW");
  }

  public async rollback(): Promise<void> {
    throw new AbapSqlError("ROLLBACK WORK is not allowed in a behavior pool: the RAP runtime ends the LUW");
  }

  public async execute(): Promise<void> {
    throw new AbapSqlError(READ_ONLY);
  }

  public async insert(): Promise<never> {
    throw new AbapSqlError(READ_ONLY);
  }

  public async update(): Promise<never> {
    throw new AbapSqlError(READ_ONLY);
  }

  public async delete(): Promise<never> {
    throw new AbapSqlError(READ_ONLY);
  }

  public async select(options: AbapSelectOptions): Promise<{ rows: AbapSqlRow[] }> {
    const text = translateSelect(options.select, options.primaryKey);
    const db = this.connection();
    const result = await withSavepoint(db, () => sql.raw<Record<string, unknown>>(text).execute(db));
    return { rows: result.rows.map((row) => Object.fromEntries(Object.entries(row).map(([name, value]) => [name, abapValue(value)]))) };
  }

  /** OPEN CURSOR: the result is read at once, FETCH hands it out package by package. */
  public async openCursor(options: AbapSelectOptions): Promise<{ fetchNextCursor(size: number): Promise<{ rows: AbapSqlRow[] }>; closeCursor(): Promise<void> }> {
    const { rows } = await this.select(options);
    let position = 0;
    return {
      fetchNextCursor: async (size: number) => {
        const count = size > 0 ? size : rows.length - position;
        const part = rows.slice(position, position + count);
        position += part.length;
        return { rows: part };
      },
      closeCursor: async () => {
        position = rows.length;
      },
    };
  }
}
